import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdir, readFile } from 'node:fs/promises';
import { chromium } from 'playwright';
import { routeSite, ORIGIN } from '../../scripts/browser-site.mjs';

test('rule selection uses rule terminology, preserves selections, and runs only enabled optional rules', { timeout: 45000 }, async () => {
  const browser = await chromium.launch({ headless: true, timeout: 10000 });
  try {
    const context = await browser.newContext({ acceptDownloads: true });
    await routeSite(context, []);
    const page = await context.newPage();
    await page.goto(ORIGIN);
    assert.equal(await page.locator('[data-step="rules"]').textContent(), '2 Rules');
    assert.equal(await page.locator('#file-next').textContent(), 'Next: choose rules →');
    const input = { type: 'FeatureCollection', features: [0, 1].map(() => ({ type: 'Feature', properties: {}, geometry: { type: 'Point', coordinates: [0, 0] } })) };
    await page.locator('#file').setInputFiles({ name: 'points.geojson', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(input)) });
    await page.locator('#file-next').click();
    assert.equal(await page.locator('#rules-title').textContent(), '2. Choose rules');
    assert.equal(await page.locator('.rule-row[data-required="true"]').count(),11);
    assert.equal(await page.locator('.rule-row[data-required="true"] input:checked:disabled').count(),11);
    assert.equal(await page.locator('#rule-table tbody tr').count(),34);
    assert.match(await page.locator('[data-rule-id="Rule-013"]').textContent(), /Geometry constraints/);
    assert.match(await page.locator('[data-rule-id="Rule-011"]').textContent(), /Geometry validity/);
    assert.match(await page.locator('[data-rule-id="Rule-001"]').textContent(), /Run diagnostics/);
    assert.equal(await page.locator('[data-category], #rule-search').count(),0);
    assert.equal(await page.locator('#rule-table tbody tr:visible').count(),34);
    assert.deepEqual(await page.locator('#rule-table thead th').allTextContents(),['Rule ID','Name','Category','Selected']);
    assert.equal(await page.locator('[data-attribute-rule], #attribute-editor').count(),0);
    await page.locator('#topology-duplicates').check();
    assert.match(await page.locator('#selection-summary').textContent(), /1 optional rules/);
    assert.match(await page.locator('#selected-rules').textContent(), /Must not have duplicates/);
    await page.locator('[data-step="review"]').click();
    assert.equal(await page.locator('#selected-rules li').count(),12);
    await page.locator('#recheck').click();
    await page.waitForFunction(() => document.getElementById('status').textContent === 'Inspection completed.');
    await page.locator('#stats [data-filter=all]').click();
    assert.equal(new Set(await page.locator('#rows .topology-problems li').evaluateAll(items => items.map(item => item.dataset.issueId))).size, 1);
    assert.equal(await page.locator('#attribute-results').count(), 0);
    await page.locator('#edit-checks').click();
    assert.equal(await page.locator('#rules-select-all, #rules-clear').count(),0);
    for (const checkbox of await page.locator('[data-topology-rule]').all()) await checkbox.check();
    assert.equal(await page.locator('[data-attribute-rule]:checked').count(),0);
    assert.equal(await page.locator('[data-topology-rule]:checked').count(),23);
    for (const checkbox of await page.locator('[data-topology-rule]').all()) await checkbox.uncheck();
    assert.equal(await page.locator('#rule-table input:checked:disabled').count(),11);
    assert.equal(await page.locator('#rule-table input:checked:not(:disabled)').count(),0);
    assert.match(await page.locator('#selection-summary').textContent(), /0 optional rules/);
    assert.match(await page.locator('#selection-notice').textContent(), /another inspection/);
    await page.locator('[data-step="results"]').click();
    await page.locator('#download').click();
    const [download] = await Promise.all([page.waitForEvent('download'), page.locator('#json').click()]);
    const report = JSON.parse(await readFile(await download.path(), 'utf8'));
    assert.equal(report.topology.options.rules.length, 1);
    assert.equal(report.attributeRules.rules.length, 0);
    await page.locator('#file').setInputFiles({ name: 'new.geojson', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(input)) });
    assert.doesNotMatch(await page.locator('#selection-notice').textContent(), /current report/);
    await mkdir('.cache', { recursive: true });
    await page.locator('#file-next').click();
    await page.screenshot({ path: '.cache/rule-selection-desktop.png', fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: '.cache/rule-selection-mobile.png', fullPage: true });
  } finally { await browser.close(); }
});
